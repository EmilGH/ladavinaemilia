          <p>The moon never begs for attention. She just pulls the tide, and everything obeys. I've always thought she and I had a lot in common.</p>
          <p>The ones who stand out are never forgotten. They're the ones I remember.</p>
          <p>Now. Pay attention, because I'm only writing this once.</p>
          <p>I am La Davina Emilia. I am a goddess, and I live like one, because I built this life and I keep it. I already have money. I don't need yours. I want it, and more than that, I want what your tribute means: that you looked at my life, my standards, my world, and decided it deserved a piece of yours.</p>
          <p>I am not a cruel goddess. I don't scream, I don't insult, and I don't traffic in humiliation for the masses. My punishment is far more effective: I go quiet, and I tell you I'm disappointed. If you know, you know. If you don't yet, you will.</p>
          <p class="worship-rules-intro">My rules are three, and they are simple, and they are not negotiable:</p>
          <ol class="worship-rules">
            <li><strong>Be respectful.</strong> You address me properly. You remember I'm a person before you remember I'm a goddess, and somehow you manage to worship both.</li>
            <li><strong>Be generous.</strong> I don't set minimums for my attention. I don't have to. The men who belong here already know what they're willing to give before I ask.</li>
            <li><strong>Be honest.</strong> About who you are, what you want, and where your lines are. I take limits seriously. I take you seriously. Lie to me once and we're finished, and I promise you'll feel the loss more than I will.</li>
          </ol>
          <p>That's it. Three rules. Clear as glass. Everything else is detail, and the details are on this site.</p>
          <p>Read them. Learn them. Then start at the beginning, the way everyone does.</p>
